// Static Lantern Hill copy: catalog, product options, bundle builder, simulated cart, coupon, demo checkout, confirmation.
// Also asserts that nothing is POSTed and no request leaves the static host.
// usage: node scripts/smoke-store.mjs http://127.0.0.1:5055/store
import { chromium } from 'playwright';
const base = process.argv[2];
const host = new URL(base).host;
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 390, height: 844 } });
const errors = [], offHost = [], posts = [];
p.on('pageerror', e => errors.push(e.message));
p.on('request', r => { if (new URL(r.url()).host !== host && !r.url().startsWith('data:')) offHost.push(r.url()); if (r.method() !== 'GET') posts.push(r.method() + ' ' + r.url()); });
const out = {};
const badge = async () => (await p.locator('[data-cart-count]').first().textContent()).trim();
await p.goto(base + '/', { waitUntil: 'networkidle' });
await p.locator('.card .add').first().click();
out.badgeAfterCard = await badge();
await p.goto(base + '/product/morning-fog/', { waitUntil: 'networkidle' });
await p.locator('label:has-text("2 lb")').click();
await p.locator('label:has-text("Espresso")').click();
await p.locator('[data-step="1"]').click();
out.pdpPrice = (await p.textContent('[data-pdp-price]')).trim();
await p.click('.pdp-form button[type=submit]');
out.badgeAfterPdp = await badge();
await p.goto(base + '/bundle/', { waitUntil: 'networkidle' });
out.ctaBefore = await p.getAttribute('[data-b-cta]', 'aria-disabled');
for (const i of [0, 6, 8]) await p.locator('.pick-item').nth(i).click();
out.bundleStatus = (await p.textContent('[data-b-status]')).trim();
out.fourthDisabled = await p.locator('.pick-item input').nth(1).isDisabled();
out.bundleTotal = (await p.textContent('[data-b-total]')).trim();
await p.click('[data-b-cta]');
out.badgeAfterBundle = await badge();
await p.goto(base + '/shop/', { waitUntil: 'networkidle' });
await p.locator('.chip[data-cat="brewing-gear"]').click();
out.shopFilter = (await p.textContent('.shop-count')).trim();
await p.goto(base + '/demo-cart/', { waitUntil: 'networkidle' });
out.cartThumbsLoaded = await p.evaluate(() => [...document.querySelectorAll('[data-cart-lines] img')].map(i => i.complete && i.naturalWidth > 0).every(Boolean) && document.querySelectorAll('[data-cart-lines] img').length === 3);
await p.locator('[data-q][data-d="1"]').first().click();
out.qtyAfterPlus = (await p.locator('.small-qty output').first().textContent()).trim();
await p.locator('[data-q][data-d="-1"]').first().click();
out.cartLines = await p.locator('[data-cart-lines] .line').count();
out.cartTotal = (await p.textContent('[data-cart-totals] .big')).replace(/\s+/g, ' ').trim();
await p.fill('#coupon', 'firstbag'); await p.click('[data-coupon] button');
out.coupon = (await p.textContent('[data-coupon-msg]')).trim();
out.totalWithCoupon = (await p.textContent('[data-cart-totals] .big')).replace(/\s+/g, ' ').trim();
await p.click('[data-cart-checkout]'); await p.waitForURL(/demo-checkout/);
await p.click('[data-place-order]');
out.checkoutErrors = await p.locator('.field.err').count() + await p.evaluate(() => document.querySelectorAll(':invalid').length);
out.stayedOnCheckout = /demo-checkout/.test(p.url());
out.focusOnFirstError = await p.evaluate(() => document.activeElement.id);
await p.fill('#co-email', 'dana@example.com'); await p.fill('#co-first', 'Dana'); await p.fill('#co-last', 'K');
await p.fill('#co-addr', '38 Orchard Lane'); await p.fill('#co-city', 'Ashgrove'); await p.fill('#co-zip', '94000');
await p.click('[data-place-order]'); await p.waitForURL(/demo-order/);
out.confirmTitle = (await p.textContent('[data-confirm-title]')).trim();
out.confirmThumbsLoaded = await p.evaluate(() => [...document.querySelectorAll('[data-confirm-order] img')].every(i => i.complete && i.naturalWidth > 0));
out.noPersonalDataStored = await p.evaluate(() => !/dana|orchard|94000|example\.com/i.test(JSON.stringify(sessionStorage)));
out.confirmUrlHasNoData = !/dana|orchard|example\.com/i.test(p.url());
out.badgeAfterOrder = await badge();
out.badgeHidden = await p.locator('[data-cart-count]').first().isHidden();
await p.goto(base + '/demo-checkout/', { waitUntil: 'networkidle' });
out.emptyCheckoutRedirects = /demo-cart/.test(p.url());
out.emptyCartHidesSummary = await p.locator('[data-cart-summary]').isHidden();
await p.screenshot({ path: process.env.SHOT || (process.env.TMPDIR || '/tmp') + '/store-confirm.png', fullPage: true });
out.errors = errors; out.offHost = [...new Set(offHost)]; out.posts = posts;
console.log(JSON.stringify(out, null, 1));
await b.close();
const ok = out.badgeAfterCard === '1' && out.badgeAfterPdp === '3' && out.badgeAfterBundle === '4' && out.cartLines === 3 && /applied/.test(out.coupon) && out.checkoutErrors > 0 && out.stayedOnCheckout && out.pdpPrice === '$52.00' && /Thanks/.test(out.confirmTitle) && out.cartThumbsLoaded && out.qtyAfterPlus === '2' && out.confirmThumbsLoaded && out.noPersonalDataStored && out.badgeHidden && out.emptyCheckoutRedirects && out.emptyCartHidesSummary && out.confirmUrlHasNoData && !errors.length && !offHost.length && !posts.length;
process.exitCode = ok ? 0 : 1;
