// README scores table, generated from the committed Lighthouse JSON in reports/ (one row per build).
// usage: node scripts/readme-scores.mjs          rewrite the table between the README markers
//        node scripts/readme-scores.mjs --check  exit 1 if the README table (or the demo count) differs from reports/
// Pages Lighthouse marks as not crawlable (the noindex utility pages) are listed separately, not mixed into the ranges.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import path from 'node:path';

const BUILDS = [
  ['Saltline Kayak Tours', 'reports/saltline'],
  ['Harbor & Pine Law (optimized)', 'reports/harbor-pine/optimized'],
  ['Harbor & Pine Law (naive, the "before")', 'reports/harbor-pine/naive'],
  ['Lantern Hill Roasters', 'reports/store'],
  ['Fernwood Makers', 'reports/makers'],
];
const DEMOS = ['saltline', 'harbor-pine', 'store', 'makers']; // shipped demos (the naive build is the Health Check's "before")
const START = '<!-- scores:start (generated by scripts/readme-scores.mjs from reports/; do not edit by hand) -->', END = '<!-- scores:end -->';

const range = (vs, f = v => String(v)) => { const lo = Math.min(...vs), hi = Math.max(...vs); return lo === hi ? f(lo) : f(lo) + ' to ' + f(hi); };
const rows = [], noindex = [], misses = [];
for (const [label, dir] of BUILDS) {
  const files = readdirSync(dir).filter(f => f.endsWith('.report.json')).sort();
  const pages = files.map(f => JSON.parse(readFileSync(path.join(dir, f), 'utf8'))).map((r, i) => ({
    name: files[i].replace('.report.json', ''),
    crawlable: r.audits['is-crawlable']?.score !== 0,
    s: Object.fromEntries(Object.entries(r.categories).map(([k, v]) => [k, Math.round(v.score * 100)])),
    lcp: r.audits['largest-contentful-paint'].numericValue / 1000,
    cls: r.audits['cumulative-layout-shift'].numericValue,
  }));
  const idx = pages.filter(p => p.crawlable);
  pages.filter(p => !p.crawlable).forEach(p => noindex.push(`${label}: ${p.name} (SEO ${p.s.seo})`));
  if (!/naive/.test(dir)) for (const p of idx) if (p.s.performance < 90 || p.s.accessibility < 95 || p.s['best-practices'] < 95 || p.s.seo < 95 || p.lcp > 2.5 || p.cls > 0.1) misses.push(`${label}: ${p.name}`);
  const col = k => range(idx.map(p => p.s[k]));
  rows.push(`| ${label} | ${idx.length} | ${col('performance')} | ${col('accessibility')} | ${col('best-practices')} | ${col('seo')} | ${range(idx.map(p => p.lcp), v => v.toFixed(1))} s | ${range(idx.map(p => +p.cls.toFixed(3)))} |`);
}
const table = [START,
  '| Build | Indexable pages | Perf | A11y | Best Pr. | SEO | LCP | CLS |', '|---|---|---|---|---|---|---|---|', ...rows, '',
  `Not crawlable by design (\`noindex, follow\`, left out of \`sitemap.xml\`): ${noindex.length ? noindex.join('; ') : 'none measured'}.`, END].join('\n');

const readme = readFileSync('README.md', 'utf8');
const a = readme.indexOf('<!-- scores:start'), b = readme.indexOf(END);
if (a < 0 || b < 0) { console.error('README markers missing'); process.exit(1); }
const next = readme.slice(0, a) + table + readme.slice(b + END.length);
const shipped = DEMOS.filter(d => existsSync(path.join('demos', d))).length;
const words = ['zero', 'one', 'two', 'three', 'four', 'five', 'six'];
const countOk = new RegExp('^' + words[shipped][0].toUpperCase() + words[shipped].slice(1) + ' WordPress demo sites', 'm').test(readme);
if (process.argv.includes('--check')) {
  const ok = next === readme && countOk && !misses.length;
  if (misses.length) console.error('Pages missing the targets: ' + misses.join(', '));
  if (!ok) console.error(next !== readme ? 'README scores table is stale: run node scripts/readme-scores.mjs' : `README intro must say "${words[shipped]}" demo sites`);
  else console.log('README scores match reports/ (' + rows.length + ' builds), demo count ' + shipped);
  process.exit(ok ? 0 : 1);
}
writeFileSync('README.md', next);
console.log('README scores table written (' + rows.length + ' builds)' + (countOk ? '' : `; WARNING: intro does not say "${words[shipped]}" demo sites`));
